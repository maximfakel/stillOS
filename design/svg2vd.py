#!/usr/bin/env python3
"""Turn the official white logo SVGs into launcher tile banners (Android VectorDrawable).

Each banner is a 266x150 canvas (the tile in the Paper mockup) with the logo centred at the size the
mockup gives it, so the tile shows exactly what the design shows. Paths are copied as they are: nothing
is redrawn or recoloured. Supports what these files use: translate() groups, solid fills, evenodd,
and userSpaceOnUse linear gradients (ivi).

    python3 design/svg2vd.py            writes launcher/app/src/main/res/drawable/banner_*.xml
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(ROOT, "..", "launcher", "app", "src", "main", "res", "drawable")
TILE_W, TILE_H = 266.0, 150.0
SVG = "{http://www.w3.org/2000/svg}"

# banner name -> (source svg relative to design/brand, logo width and height on the 266x150 tile)
LOGOS = {
    "banner_kinopoisk": ("paper/kinopoisk.svg", 197, 43),
    "banner_vk_video": ("paper/vk_video.svg", 214, 46),
    "banner_ivi": ("ivi/Logotype/Monochrome/White/White.svg", 122, 64),
    "banner_rutube": ("rutube/Logo_RUTUBE/Logo/SVG/Logo_RUTUBE_white_mono.svg", 190, 32),
    "banner_google_play": ("paper/google_play.svg", 180, 36),
    "banner_okko": ("okko/okko_logo_white.svg", 140, 50),
    "banner_premier": ("paper/premier.svg", 200, 25),
    "banner_rustore": ("rustore/RuStore_White_Logo.svg", 170, 43),
    "banner_youtube": ("YouTube_Logo/yt_logo_white_digital.svg", 180, 40),
}


def color(value, opacity=1.0):
    """SVG colour to #AARRGGBB."""
    v = (value or "").strip().lower()
    if v in ("white", "#fff"):
        v = "#ffffff"
    if v in ("black", "#000"):
        v = "#000000"
    if not re.fullmatch(r"#[0-9a-f]{6}", v):
        raise ValueError("unsupported colour %r" % value)
    return "#%02X%s" % (round(255 * opacity), v[1:].upper())


def gradients(svg):
    found = {}
    for g in svg.iter(SVG + "linearGradient"):
        if g.get("gradientUnits") != "userSpaceOnUse":
            raise ValueError("only userSpaceOnUse gradients are supported")
        stops = [(float(s.get("offset")), color(s.get("stop-color"), float(s.get("stop-opacity", "1"))))
                 for s in g.iter(SVG + "stop")]
        found[g.get("id")] = (g.get("x1"), g.get("y1"), g.get("x2"), g.get("y2"), stops)
    return found


def emit(node, grads, out, indent, inherited_fill):
    tag = node.tag.replace(SVG, "")
    pad = "    " * indent
    if tag == "g":
        tr = node.get("transform")
        attrs = ""
        if tr:
            m = re.fullmatch(r"translate\(\s*([-\d.]+)[\s,]+([-\d.]+)\s*\)", tr.strip())
            if not m:
                raise ValueError("unsupported transform %r" % tr)
            attrs = ' android:translateX="%s" android:translateY="%s"' % m.groups()
        out.append("%s<group%s>" % (pad, attrs))
        for child in node:
            emit(child, grads, out, indent + 1, node.get("fill", inherited_fill))
        out.append("%s</group>" % pad)
    elif tag == "path":
        d = node.get("d")
        fill = node.get("fill", inherited_fill)
        evenodd = node.get("fill-rule") == "evenodd"
        attrs = ' android:pathData="%s"' % d
        if evenodd:
            attrs += ' android:fillType="evenOdd"'
        m = re.fullmatch(r"url\(#([^)]+)\)", fill or "")
        if m:
            x1, y1, x2, y2, stops = grads[m.group(1)]
            out.append("%s<path%s>" % (pad, attrs))
            out.append('%s    <aapt:attr name="android:fillColor">' % pad)
            out.append('%s        <gradient android:type="linear" android:startX="%s" android:startY="%s"'
                       ' android:endX="%s" android:endY="%s">' % (pad, x1, y1, x2, y2))
            for off, c in stops:
                out.append('%s            <item android:offset="%s" android:color="%s" />' % (pad, off, c))
            out.append("%s        </gradient>" % pad)
            out.append("%s    </aapt:attr>" % pad)
            out.append("%s</path>" % pad)
        else:
            out.append('%s<path%s android:fillColor="%s" />' % (pad, attrs, color(fill)))
    elif tag in ("defs", "linearGradient", "stop", "title", "desc"):
        return
    else:
        raise ValueError("unsupported element <%s>" % tag)


def convert(src, logo_w, logo_h):
    svg = ET.parse(src).getroot()
    vx, vy, vw, vh = (float(x) for x in svg.get("viewBox").replace(",", " ").split())
    s = min(logo_w / vw, logo_h / vh)
    tx = (TILE_W - vw * s) / 2 - vx * s
    ty = (TILE_H - vh * s) / 2 - vy * s
    grads = gradients(svg)
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           "<!-- Generated by design/svg2vd.py from design/brand/%s. Do not edit: the logo is the brand's own"
           " artwork; see design/brand/NOTICE.md. -->" % os.path.relpath(src, os.path.join(ROOT, "brand")),
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    xmlns:aapt="http://schemas.android.com/aapt"',
           '    android:width="200dp" android:height="%.2fdp"' % (200 * TILE_H / TILE_W),
           '    android:viewportWidth="%g" android:viewportHeight="%g">' % (TILE_W, TILE_H),
           '    <group android:translateX="%.3f" android:translateY="%.3f" android:scaleX="%.5f" android:scaleY="%.5f">'
           % (tx, ty, s, s)]
    for child in svg:
        emit(child, grads, out, 2, svg.get("fill", "#FFFFFF"))
    out += ["    </group>", "</vector>", ""]
    return "\n".join(out)


def main():
    for name, (rel, w, h) in LOGOS.items():
        src = os.path.join(ROOT, "brand", rel)
        dst = os.path.join(OUT, name + ".xml")
        with open(dst, "w", encoding="utf-8") as f:
            f.write(convert(src, w, h))
        print("wrote", os.path.relpath(dst, os.path.join(ROOT, "..")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
